    ON public.inventory_movements;
CREATE TRIGGER inventory_movements_immutable
BEFORE UPDATE OR DELETE ON public.inventory_movements
FOR EACH ROW EXECUTE FUNCTION public.nualco_prevent_movement_change();

REVOKE ALL ON FUNCTION public.nualco_current_role_id() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.nualco_role_name() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.nualco_is_admin() FROM PUBLIC;
