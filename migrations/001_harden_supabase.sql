CREATE TABLE IF NOT EXISTS public.inventory_movements (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_kind text NOT NULL
        CHECK (inventory_kind IN ('raw_material', 'finished_goods', 'furnace_oil')),
    lot_id integer REFERENCES public.raw_material_inventory(lot_id),
    bundle_id integer REFERENCES public.finished_goods_inventory(bundle_id),
    batch_id text REFERENCES public.production_batch(batch_id),
    packing_list_id integer REFERENCES public.packing_list(packing_list_id),
    quantity_delta numeric(14, 4) NOT NULL CHECK (quantity_delta <> 0),
    unit text NOT NULL CHECK (unit IN ('kg', 'litre', 'piece')),
    movement_type text NOT NULL,
    source_type text,
    source_id text,
    idempotency_key text NOT NULL UNIQUE,
    actor_employee_id text REFERENCES public.employees(employee_id),
    occurred_at timestamptz NOT NULL DEFAULT now(),
    reason text,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    CHECK (
        (inventory_kind = 'raw_material' AND lot_id IS NOT NULL AND bundle_id IS NULL)
        OR (inventory_kind = 'finished_goods' AND bundle_id IS NOT NULL AND lot_id IS NULL)
        OR (inventory_kind = 'furnace_oil' AND lot_id IS NULL AND bundle_id IS NULL)
    )
);

