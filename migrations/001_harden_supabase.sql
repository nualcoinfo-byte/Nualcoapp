CREATE OR REPLACE FUNCTION public.nualco_current_role_id()
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT e.role_id
    FROM public.employees e
    WHERE lower(e.employee_id) = lower(
        NULLIF(current_setting('nualco.employee_id', true), '')
    )
      AND lower(COALESCE(e.status, 'Active')) = 'active'
    LIMIT 1
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_role_name()
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT lower(COALESCE(r.role_name, ''))
    FROM public.roles r
    WHERE r.role_id = public.nualco_current_role_id()
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT COALESCE(public.nualco_role_name() = 'admin', false)
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_can(p_table text, p_action text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT
        public.nualco_is_admin()
        OR EXISTS (
            SELECT 1
            FROM public.role_permissions rp
            JOIN public.section_table_permissions sp
              ON sp.section_key = rp.section_key
            WHERE rp.role_id = public.nualco_current_role_id()
              AND sp.table_name = lower(p_table)
              AND CASE lower(p_action)
                    WHEN 'select' THEN sp.can_select
                    WHEN 'insert' THEN sp.can_insert
                    WHEN 'update' THEN sp.can_update
                    WHEN 'delete' THEN sp.can_delete
                    ELSE false
                  END
        )
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_auth_record(p_employee_id text)
RETURNS TABLE (
    employee_id text,
    first_name text,
    last_name text,
    email text,
    role_id integer,
    role_name text,
    status text,
    password_hash text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT e.employee_id::text, e.first_name::text, e.last_name::text,
           e.email::text, e.role_id, r.role_name::text, e.status::text,
           e.password_hash::text
    FROM public.employees e
    LEFT JOIN public.roles r ON r.role_id = e.role_id
    WHERE lower(e.employee_id) = lower(p_employee_id)
    LIMIT 1
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_bootstrap_admins()
RETURNS TABLE (
    employee_id text,
    first_name text,
    last_name text,
    email text,
    role_id integer,
    role_name text,
    status text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT e.employee_id::text, e.first_name::text, e.last_name::text,
           e.email::text, e.role_id, r.role_name::text, e.status::text
    FROM public.employees e
    JOIN public.roles r ON r.role_id = e.role_id
    WHERE lower(r.role_name) = 'admin'
      AND lower(COALESCE(e.status, 'Active')) = 'active'
      AND NOT EXISTS (
          SELECT 1 FROM public.employees x
          WHERE NULLIF(trim(x.password_hash), '') IS NOT NULL
      )
    ORDER BY e.employee_id
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_passwords_initialized()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
    SELECT EXISTS (
        SELECT 1 FROM public.employees
        WHERE NULLIF(trim(password_hash), '') IS NOT NULL
    )
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_set_first_admin_password(
    p_employee_id text,
    p_password_hash text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $fn$
BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('nualco:first-admin-password'));
    IF EXISTS (
        SELECT 1 FROM public.employees
        WHERE NULLIF(trim(password_hash), '') IS NOT NULL
    ) THEN
        RETURN false;
    END IF;
    UPDATE public.employees e
       SET password_hash = p_password_hash,
           password_updated_at = now()
      FROM public.roles r
     WHERE e.role_id = r.role_id
       AND lower(r.role_name) = 'admin'
       AND lower(e.employee_id) = lower(p_employee_id)
       AND lower(COALESCE(e.status, 'Active')) = 'active';
    RETURN FOUND;
END
$fn$;

CREATE OR REPLACE FUNCTION public.nualco_prevent_movement_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $fn$
BEGIN
    RAISE EXCEPTION 'inventory_movements is immutable; post a compensating movement';
END
$fn$;

