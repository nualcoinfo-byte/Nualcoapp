REVOKE ALL ON FUNCTION public.nualco_auth_record(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.nualco_bootstrap_admins() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.nualco_passwords_initialized() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.nualco_set_first_admin_password(text, text) FROM PUBLIC;

